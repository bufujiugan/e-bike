CREATE TABLE bike_after_sales_notification (
    id BIGINT PRIMARY KEY AUTO_INCREMENT,
    case_id BIGINT NOT NULL,
    event_id BIGINT NOT NULL COMMENT '来源业务审计事件，单事件每种受众只入队一次',
    event_type VARCHAR(64) NOT NULL,
    audience VARCHAR(16) NOT NULL COMMENT 'CUSTOMER/STAFF',
    original_recipient VARCHAR(254) NULL COMMENT '事件发生时客户地址快照；STAFF使用配置邮箱',
    recipient VARCHAR(254) NULL COMMENT '当前收件地址，人工更正须审计',
    message_key CHAR(36) NOT NULL COMMENT '重试保持相同Message-ID',
    subject VARCHAR(255) NOT NULL,
    body TEXT NOT NULL COMMENT '公开模板快照，不包含内部备注或文件对象键',
    status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
    attempt_count INT NOT NULL DEFAULT 0,
    revision INT NOT NULL DEFAULT 1,
    next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    claim_token CHAR(36) NULL,
    claimed_until DATETIME(3) NULL,
    last_error VARCHAR(64) NULL COMMENT '固定错误代码，不存SMTP异常原文或凭据',
    sent_at DATETIME(3) NULL COMMENT 'SMTP接受时间，并非最终送达证明',
    created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
    updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
    UNIQUE KEY uk_bike_after_sales_notification_event(event_id,audience),
    UNIQUE KEY uk_bike_after_sales_notification_message(message_key),
    KEY idx_bike_after_sales_notification_due(status,next_attempt_at),
    KEY idx_bike_after_sales_notification_case(case_id,id),
    CONSTRAINT fk_bike_after_sales_notification_case FOREIGN KEY(case_id) REFERENCES bike_after_sales_case(id),
    CONSTRAINT ck_bike_after_sales_notification_audience CHECK(audience IN('CUSTOMER','STAFF')),
    CONSTRAINT ck_bike_after_sales_notification_status CHECK(status IN('PENDING','SENDING','RETRY','SENT','FAILED','BLOCKED')),
    CONSTRAINT ck_bike_after_sales_notification_counts CHECK(attempt_count>=0 AND revision>0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='售后事务邮件队列，默认禁用真实发送';
