package com.bike.server.aftersales;

import static com.bike.server.aftersales.AfterSalesAccess.*;
import com.bike.server.common.BusinessException;
import com.bike.server.common.CurrentOperator;
import com.bike.server.production.ProductionFileStore;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.*;
import java.nio.file.Files;
import java.util.*;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;
import org.springframework.core.io.Resource;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.support.TransactionSynchronization;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import org.springframework.web.multipart.MultipartFile;

@Service
public class AfterSalesAttachmentService {
    private static final Logger LOG = LoggerFactory.getLogger(AfterSalesAttachmentService.class);
    private static final Set<String> CATEGORIES = Set.of("FAULT_IMAGE", "FAULT_VIDEO", "FRAME_SN", "MOTOR_SN", "BATTERY_SN", "DISPLAY_SN", "PURCHASE_PROOF", "DIAGNOSTIC", "TECHNICAL", "OTHER");
    private static final ObjectMapper JSON = new ObjectMapper().findAndRegisterModules();
    private final AfterSalesMapper mapper;
    private final ProductionFileStore files;
    private final AfterSalesUploadValidator validator;
    public AfterSalesAttachmentService(AfterSalesMapper mapper, ProductionFileStore files, AfterSalesUploadValidator validator) {
        this.mapper = mapper; this.files = files; this.validator = validator;
    }
    public List<AfterSalesAttachmentView> list(long caseId) {
        requireCaseContent(); requireCaseScope(mapper, mapper.selectById(caseId));
        return mapper.selectAttachments(caseId, canReadInternal());
    }
    public Download download(long caseId, long attachmentId) {
        requireCaseContent(); requireCaseScope(mapper, mapper.selectById(caseId));
        var attachment = mapper.selectStoredAttachment(attachmentId);
        if (attachment == null || !Objects.equals(attachment.caseId(), caseId)) throw missing();
        if (!"CUSTOMER".equals(attachment.visibility()) && !canReadInternal()) throw new BusinessException("FORBIDDEN", "无权访问内部附件");
        // Keys are generated by this service and resolved only from a scoped attachment row.
        if (attachment.objectKey() == null || !attachment.objectKey().matches("(?:local:|cos:production/)after-sales-[0-9a-f-]{36}\\.(?:jpg|jpeg|png|pdf|mp4|txt|log|csv|json)"))
            throw new BusinessException("ATTACHMENT_STORAGE_INVALID", "附件存储信息不合法");
        return new Download(attachment.fileName(), attachment.contentType(), attachment.fileSize(), files.read(attachment.objectKey()));
    }

    @Transactional(rollbackFor = Exception.class)
    public List<AfterSalesAttachmentView> upload(long caseId, List<MultipartFile> uploads, String visibility, String category, Long messageId) throws IOException {
        requireCommunicationWrite();
        mutableCase(mapper.selectById(caseId));
        String scope = visibility == null || visibility.isBlank() ? "CUSTOMER" : visibility.trim();
        String purpose = category == null || category.isBlank() ? "OTHER" : category.trim();
        if (!Set.of("CUSTOMER", "INTERNAL").contains(scope)) throw invalid("附件可见范围不合法");
        if (scope.equals("INTERNAL") && !canReadInternal()) throw new BusinessException("PERMISSION_DENIED", "当前账号不能上传内部附件");
        if (!CATEGORIES.contains(purpose)) throw invalid("附件用途不合法");
        if (uploads == null || uploads.isEmpty() || uploads.size() > 5) throw invalid("每次须上传1至5个附件");
        long requestedSize = 0;
        for (var upload : uploads) {
            if (upload == null || upload.getSize() <= 0 || upload.getSize() > AfterSalesUploadValidator.VIDEO_LIMIT) throw invalid("附件不能为空且单文件不能超过50MB");
            requestedSize += upload.getSize();
            if (requestedSize > AfterSalesUploadValidator.BATCH_LIMIT) throw invalid("一次上传的附件总大小不能超过150MB");
        }
        var prepared = new ArrayList<AfterSalesUploadValidator.PreparedUpload>();
        var keys = new ArrayList<String>();
        try {
            for (var upload : uploads) prepared.add(validator.prepare(upload));
            mutableCase(mapper.selectForUpdate(caseId));
            if (messageId != null) {
                var message = mapper.selectMessageById(messageId);
                if (message == null || !Objects.equals(message.caseId(), caseId)) throw invalid("关联留言不属于当前案例");
                if (!Objects.equals(message.authorId(), CurrentOperator.id())) throw new BusinessException("FORBIDDEN", "只能给本人留言添加附件");
                if (!scope.equals(message.visibility())) throw invalid("留言附件必须与留言的可见范围一致");
            }
            if (!TransactionSynchronizationManager.isActualTransactionActive()) throw new IllegalStateException("附件上传必须在事务中执行");
            TransactionSynchronizationManager.registerSynchronization(new TransactionSynchronization() {
                @Override public void afterCompletion(int status) { if (status != STATUS_COMMITTED) cleanup(keys); }
            });
            var results = new ArrayList<AfterSalesAttachmentView>();
            for (var file : prepared) {
                String key = files.key("after-sales-" + UUID.randomUUID() + "." + file.extension());
                keys.add(key); // Include partially written objects in rollback cleanup.
                try (var input = Files.newInputStream(file.path())) { files.write(key, input, file.size(), file.contentType()); }
                if (mapper.insertAttachment(caseId, messageId, key, file.fileName(), file.contentType(), file.size(), file.sha256(), scope, purpose, CurrentOperator.id()) != 1)
                    throw new BusinessException("AFTER_SALES_UPDATE_FAILED", "附件元数据保存失败");
                Long id = mapper.selectInsertedId();
                if (id == null) throw new BusinessException("AFTER_SALES_UPDATE_FAILED", "附件保存后无法读取");
                var saved = mapper.selectAttachmentView(id);
                if (saved == null || !Objects.equals(saved.caseId(), caseId)) throw new BusinessException("AFTER_SALES_UPDATE_FAILED", "附件保存后无法读取");
                results.add(saved);
            }
            if (mapper.touchCase(caseId, CurrentOperator.id()) != 1) throw new BusinessException("AFTER_SALES_UPDATE_FAILED", "案例更新时间保存失败");
            if (mapper.insertAudit(caseId, scope.equals("INTERNAL") ? "INTERNAL_ATTACHMENTS_ADDED" : "ATTACHMENTS_ADDED", CurrentOperator.id(),
                CurrentOperator.username(), null, JSON.writeValueAsString(results), CurrentOperator.clientIp()) != 1)
                throw new BusinessException("AFTER_SALES_AUDIT_FAILED", "附件操作历史保存失败");
            AfterSalesNotifications.enqueue(mapper,caseId,scope.equals("INTERNAL")?"INTERNAL_ATTACHMENTS_ADDED":"ATTACHMENTS_ADDED",null);
            return List.copyOf(results);
        } catch (IOException | RuntimeException error) {
            cleanup(keys);
            throw error;
        } finally {
            for (var file : prepared) try { file.close(); } catch (IOException error) { LOG.warn("售后附件临时文件清理失败", error); }
        }
    }
    private void mutableCase(AfterSalesCaseView c) {
        requireCaseScope(mapper, c);
        if (Set.of("CLOSED", "REJECTED").contains(c.getStatus())) throw new BusinessException("INVALID_STATUS_TRANSITION", "已归档或拒绝案例不能继续上传附件");
    }
    private void cleanup(List<String> keys) {
        for (String key : List.copyOf(keys)) try { files.remove(key); keys.remove(key); }
        catch (Exception error) { LOG.error("售后附件事务回滚后对象清理失败 key={}", key, error); }
    }
    private static BusinessException invalid(String message) { return new BusinessException("INVALID_PARAMETER", message); }
    private static BusinessException missing() { return new BusinessException("ATTACHMENT_NOT_FOUND", "附件不存在"); }
    public record Download(String fileName, String contentType, long size, Resource resource) {}
}
