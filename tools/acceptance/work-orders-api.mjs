import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { writeFile } from 'node:fs/promises';

if (process.env.BIKE_ACCEPTANCE_WRITE !== 'isolated') throw new Error('仅允许专用验收库');
if (!process.env.BIKE_TEST_PASSWORD) throw new Error('缺少 BIKE_TEST_PASSWORD');
const base = process.env.BIKE_API_URL || 'http://127.0.0.1:18180';
const prefix = `WOQA${Date.now().toString(36).toUpperCase()}`;
const evidence = { prefix, startedAt: new Date().toISOString(), checks: [], fixtures: {} };
let token;
async function req(path, body, code = 'SUCCESS', method = body === undefined ? 'GET' : 'POST') {
  const response = await fetch(base + path, { method, headers: { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}) }, body: body === undefined ? undefined : JSON.stringify(body) });
  const result = await response.json();
  assert.equal(result.code, code, `${path}: HTTP ${response.status} ${result.code} ${result.message}`);
  if (code === 'SUCCESS') assert(response.ok);
  return result.data;
}
function pass(name) { evidence.checks.push({ name, passed: true }); console.log(`PASS ${name}`); }
try {
  const login = await req('/api/auth/login', { username: process.env.BIKE_TEST_USERNAME || 'admin', password: process.env.BIKE_TEST_PASSWORD });
  token = login.accessToken;
  assert.equal(login.mustChangePassword, false);
  const master = (type, suffix) => req(`/api/master/${type}`, { code: prefix + suffix, name: '流程验收' + prefix + suffix });
  const model = await master('models', 'MODEL'), customer = await master('customers', 'CUSTOMER');
  const warehouse = await master('warehouses', 'WAREHOUSE');
  const location = await req(`/api/master/warehouses/${warehouse.id}/locations`, { code: prefix + 'LOC', name: '验收库位' + prefix });
  const templates = await req('/api/production/templates');
  await req('/api/production/skus', { modelId: model.id, skuCode: prefix + 'SKU', productName: '生产全流程验收', specification: '48V', ean: '5901234123457', upc: '036000291452', templateId: templates[0].id, enabled: true });
  const sku = (await req('/api/production/skus')).find(row => row.skuCode === prefix + 'SKU');
  const parts = async suffix => {
    const codes = Object.fromEntries(['FRAME', 'MOTOR', 'BATTERY', 'DISPLAY'].map(type => [type, prefix + suffix + type]));
    for (const type of ['MOTOR', 'BATTERY', 'DISPLAY']) await req('/api/parts', { partSn: codes[type], partType: type, qcStatus: 'PASSED' });
    return codes;
  };
  const codes = await parts('A');
  const command = { requestId: randomUUID(), skuId: sku.id, batchNo: prefix, plannedQuantity: 2 };
  const workOrder = await req('/api/production/work-orders', command);
  assert.equal(workOrder.tasks.total, 0);
  assert.equal((await req('/api/production/work-orders', command)).id, workOrder.id);
  await req('/api/production/work-orders', { ...command, plannedQuantity: 3 }, 'IDEMPOTENCY_CONFLICT');
  await req('/api/production/work-orders', { ...command, requestId: randomUUID(), plannedQuantity: 0 }, 'INVALID_PARAMETER');
  pass('创建多车工单、重试幂等、请求内容冲突和数量校验');
  const path = `/api/production/work-orders/${workOrder.id}`;
  const scan = (taskId, code, expectedType, error) => req(path + '/scan', { taskId, code, expectedType }, error);
  await req(path + '/pause', { reason: '验收暂停' });
  await scan(null, codes.FRAME, 'FRAME', 'WORK_ORDER_NOT_RELEASED');
  assert.equal((await req(path)).tasks.total, 0);
  await req(path + '/resume', { reason: '验收恢复' });
  pass('暂停阻断扫码且不建单车，恢复后可生产');
  await scan(null, prefix + 'UNKNOWN', 'MOTOR', 'PART_NOT_FOUND');
  assert.equal((await req(path)).tasks.total, 0);
  const failures = await req(`/api/production/scan-failures?keyword=${prefix}UNKNOWN`);
  assert.equal(failures.total, 1);
  pass('失败首码回滚单车及名额，独立保留失败记录');
  let vehicle = await scan(null, codes.DISPLAY, 'DISPLAY');
  assert.equal(vehicle.scans.length, 1);
  assert.equal((await scan(vehicle.id, codes.DISPLAY, 'DISPLAY')).scans.length, 1);
  assert.equal((await req(`/api/production/tasks/${vehicle.id}`)).scans.length, 1);
  pass('首码自动建单车、重复扫码幂等、断点恢复');
  const other = await req('/api/production/work-orders', { ...command, requestId: randomUUID(), batchNo: prefix + 'OTHER', plannedQuantity: 1 });
  await req(`/api/production/work-orders/${other.id}/scan`, { taskId: vehicle.id, code: codes.MOTOR, expectedType: 'MOTOR' }, 'WORK_ORDER_TASK_MISMATCH');
  pass('禁止跨工单续扫其他单车');
  const reserved = await scan(null, codes.MOTOR, 'MOTOR');
  await scan(null, prefix + 'EXTRA', 'FRAME', 'WORK_ORDER_QUANTITY_REACHED');
  await req(`/api/production/tasks/${reserved.id}/cancel`, { reason: '取消验收，释放部件和名额' });
  assert.equal((await req(path)).inProgressQuantity, 1);
  for (const type of ['MOTOR', 'BATTERY', 'FRAME']) vehicle = await scan(vehicle.id, codes[type], type);
  assert.equal(vehicle.status, 'COMPLETED'); assert(vehicle.qrCode);
  pass('计划数量上限拦截、取消释放占用、乱序四码完成');
  const secondCodes = await parts('B');
  let second = await scan(null, secondCodes.FRAME, 'FRAME');
  for (const type of ['BATTERY', 'DISPLAY', 'MOTOR']) second = await scan(second.id, secondCodes[type], type);
  const completed = await req(path);
  assert.equal(completed.status, 'COMPLETED'); assert.equal(completed.completedQuantity, 2); assert.equal(completed.inProgressQuantity, 0);
  await scan(null, prefix + 'EXTRA', 'FRAME', 'WORK_ORDER_NOT_RELEASED');
  pass('一张工单生产两车，满额自动完工且禁止超产');
  const filtered = await req(`/api/production/work-orders?keyword=${prefix}&skuId=${sku.id}&status=COMPLETED`);
  assert(filtered.records.some(row => row.id === workOrder.id));
  pass('工单列表按 SKU、批次和完成状态筛选');
  const prints = await req(`/api/production/tasks/${vehicle.id}/prints`); assert.equal(prints.length, 1);
  await req(`/api/production/tasks/${vehicle.id}/complete`, {});
  assert.equal((await req(`/api/production/tasks/${vehicle.id}/prints`)).length, 1);
  const label = await fetch(base + `/api/production/prints/${prints[0].id}/label`, { headers: { Authorization: `Bearer ${token}` } });
  assert(label.ok); assert((await label.text()).includes(codes.FRAME));
  await req(`/api/production/prints/${prints[0].id}/claim`, { terminal: 'isolated-no-hardware' });
  await req(`/api/production/prints/${prints[0].id}/result`, { status: 'FAILED', message: '验收模拟失败，未操作物理打印机' });
  const reprint = await req(`/api/production/prints/${prints[0].id}/reprint`, { reason: '验收补打' });
  assert.notEqual(reprint.id, prints[0].id);
  pass('标签真实渲染、首打不重复、领取回报及补打');
  const issue = await req('/api/production/issues', { code: vehicle.qrCode, reason: prefix + '隔离验收' });
  const issues = await req(`/api/production/issues?keyword=${prefix}`);
  assert(issues.records.some(row => row.id === issue.id));
  await req('/api/stock-in', { vehicleQrCode: vehicle.qrCode, warehouseId: warehouse.id, locationId: location.id }, 'PRODUCTION_QUARANTINED');
  await req(`/api/production/issues/${issue.id}/resolve`, { reason: '验收解除隔离' });
  pass('异常列表可查询，隔离车辆阻断入库，解除后放行');
  for (const task of [vehicle, second]) await req('/api/stock-in', { vehicleQrCode: task.qrCode, warehouseId: warehouse.id, locationId: location.id });
  const stock = await req(`/api/production/inventory?skuId=${sku.id}&warehouseId=${warehouse.id}`);
  assert.equal(stock.reduce((sum, row) => sum + row.physicalQty, 0), 2);
  pass('两台车真实入库，SKU 实物库存为 2');
  const lockCommand = { requestId: randomUUID(), customerId: customer.id, agentId: null, items: [{ skuId: sku.id, quantity: 2 }], remark: prefix };
  const [lock] = await req('/api/sku-locks', lockCommand);
  assert.equal((await req('/api/sku-locks', lockCommand))[0].id, lock.id);
  const conversion = { customerId: customer.id, quantity: 2, requestId: randomUUID() };
  const order = await req(`/api/inventory-locks/${lock.id}/orders`, conversion);
  assert.equal((await req(`/api/inventory-locks/${lock.id}/orders`, conversion)).id, order.id);
  await req(`/api/orders/${order.id}/confirm`, {});
  pass('SKU 锁定、锁定转订单及重试幂等、订单确认');
  await req('/api/stock-out', { customerId: customer.id, orderId: order.id, vehicleQrCodes: [vehicle.qrCode] });
  assert.equal((await req(`/api/orders/${order.id}`)).shippedQty, 1);
  await req('/api/stock-out', { customerId: customer.id, orderId: order.id, vehicleQrCodes: [second.qrCode] });
  assert.equal((await req(`/api/orders/${order.id}`)).shippedQty, 2);
  pass('订单分两批出库，已发数量从 1 累加至 2');
  for (const [type, code] of [['frame', codes.FRAME], ['part', codes.BATTERY], ['qr', vehicle.qrCode]]) {
    const trace = await req(`/api/trace/${type}/${encodeURIComponent(code)}`);
    assert.equal(trace.vehicle.frameSn, codes.FRAME); assert.equal(trace.stockInRecords.length, 1); assert.equal(trace.stockOutRecords.length, 1); assert.equal(trace.bindingHistory.length, 3);
  }
  pass('车架、部件、总码均可追溯生产绑定及出入库');
  // 为真实浏览器验收保留独立 SKU、部件与空白工单，所有数据均在专用库。
  const browserCodes = await parts('WEB'), pdaCodes = await parts('PDA');
  const pdaWorkOrder = await req('/api/production/work-orders', { ...command, requestId: randomUUID(), batchNo: prefix + 'PDA', plannedQuantity: 1 });
  evidence.fixtures = { skuId: sku.id, skuCode: sku.skuCode, modelId: model.id, customerId: customer.id, warehouseId: warehouse.id, warehouseName: warehouse.name, locationId: location.id, locationName: location.name, workOrderId: workOrder.id, orderId: order.id, browserCodes, pdaCodes, pdaWorkOrder };
} catch (error) { evidence.error = error.message; console.error(error.message); process.exitCode = 1; }
evidence.finishedAt = new Date().toISOString();
if (process.env.BIKE_ACCEPTANCE_REPORT) await writeFile(process.env.BIKE_ACCEPTANCE_REPORT, JSON.stringify(evidence, null, 2) + '\n');
console.log(`工单全流程 ${evidence.checks.length} 项；${evidence.error ? '失败' : '通过'}`);
